'use strict'

const { execFileSync } = require('node:child_process')
const { lstatSync } = require('node:fs')
const { join } = require('node:path')

function validateProductManifest(root, mode, stage, path, name) {
  if (
    !/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(name) ||
    name === '.' ||
    name === '..' ||
    stage !== '0' ||
    mode !== '100644'
  )
    throw new Error(`noncanonical Product manifest: ${path}`)
  for (const part of ['apps', `apps/${name}`, path]) {
    const stat = lstatSync(join(root, part))
    if (stat.isSymbolicLink() || (part === path ? !stat.isFile() : !stat.isDirectory()))
      throw new Error(`noncanonical Product manifest: ${path}`)
  }
}

// The index is the inventory: untracked apps cannot silently expand a Dependabot scan.
function productManifestDirectories(root, zones) {
  const entries = execFileSync('git', ['ls-files', '--stage', '-z', '--', 'apps/'], {
    cwd: root,
    encoding: 'utf8',
  })
    .split('\0')
    .filter(Boolean)
  const directories = []
  for (const entry of entries) {
    const match = /^(\d+) [0-9a-f]+ (\d)\t(apps\/([^/]+)\/package\.json)$/.exec(entry)
    if (!match) continue
    const [, mode, stage, path, name] = match
    if (
      (zones.protected_files || []).includes(path) ||
      (zones.protected_prefixes || []).some((prefix) => path.startsWith(prefix))
    )
      continue
    validateProductManifest(root, mode, stage, path, name)
    directories.push(`/apps/${name}`)
  }
  directories.sort()
  if (!directories.length) throw new Error('no tracked Product app manifests')
  return directories
}

function renderProductDependabot(directories) {
  if (
    !(Array.isArray(directories) && directories.length) ||
    directories.some(
      (p, i) => !/^\/apps\/[A-Za-z0-9][A-Za-z0-9._-]*$/.test(p) || (i && directories[i - 1] >= p),
    )
  )
    throw new Error('expected sorted unique Product app directories')
  return `# Generated by scripts/kit/configure-product-dependabot.cjs; do not edit.
# Scan scope is not a lockfile mutation boundary. Review the entire bun.lock.
version: 2
updates:
  - package-ecosystem: bun
    directories:
${directories.map((p) => `      - ${JSON.stringify(p)}\n`).join('')}    schedule:
      interval: weekly
      day: monday
    open-pull-requests-limit: 10
    groups:
      bun-dependencies:
        patterns:
          - "*"
        update-types:
          - minor
          - patch
        exclude-patterns:
          - "wrangler"
      vitest:
        patterns:
          - "vitest"
          - "@vitest/*"
        update-types:
          - major
    cooldown:
      default-days: 3
      semver-major-days: 7
      semver-minor-days: 3
      semver-patch-days: 3
    labels:
      - dependencies
`
}

module.exports = { productManifestDirectories, renderProductDependabot }
